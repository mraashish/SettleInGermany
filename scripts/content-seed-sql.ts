/// <reference types="node" />
/**
 * Generates supabase/seed.sql and supabase/seed-update.sql from the bundled seed
 * content (src/content/seed.ts). Run: npm run db:seed-sql
 *
 * seed.sql (new database): every document is inserted as a draft; documents that
 * pass `content_validate` are then published in one release. The rest stay as
 * drafts for editors to finish in the CMS.
 *
 * seed-update.sql (existing database): brings the bundled content in. It overwrites
 * documents with the same key — editors' changes to those documents are replaced
 * (their history stays in content_revisions) — and publishes them in one release.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { COLLECTIONS, type CollectionName, documentKey } from '../src/content/collections';
import * as seed from '../src/content/seed';

function build(update: boolean): string {
  const lines: string[] = [
    '-- GENERATED by scripts/content-seed-sql.ts — do not edit by hand.',
    update
      ? '-- Updates an existing database with the content from src/content/seed.ts and publishes it.'
      : '-- Initial content imported from src/content/seed.ts.',
    'begin;',
  ];
  const keys: string[] = [];
  for (const c of COLLECTIONS as CollectionName[]) {
    const value = (seed as Record<string, unknown>)[c];
    const docs = (Array.isArray(value) ? value : [value]) as Record<string, unknown>[];
    docs.forEach((d, i) => {
      const json = JSON.stringify(d);
      if (json.includes('$seed$')) throw new Error('Unexpected delimiter in content');
      const key = documentKey(c, d).replace(/'/g, "''");
      keys.push(`('${c}', '${key}')`);
      const conflict = update
        ? 'on conflict (collection, key) do update set data = excluded.data, sort_order = excluded.sort_order'
        : 'on conflict (collection, key) do nothing';
      lines.push(
        `insert into public.content_documents (collection, key, data, sort_order) values ('${c}', '${key}', $seed$${json}$seed$::jsonb, ${i * 10}) ${conflict};`,
      );
    });
  }
  const inBundle = `(collection, key) in (${keys.join(', ')})`;
  if (update) {
    // Old sample documents from earlier app versions ("[Bank A]", "[date]", example.com,
    // empty city pages) are removed. Everything an editor wrote stays.
    lines.push(
      `delete from public.content_documents where not ${inBundle} and (
  data::text ~ '\\[(Bank|Provider|date|—|X\\]|Phone|What|When|Deadline|Asian|Nepali|Hindu|One-line|Two-line|€)'
  or data::text like '%example.com%'
  or (collection = 'cities' and coalesce(jsonb_array_length(data -> 'facts'), 0) = 0
      and coalesce(jsonb_array_length(data -> 'appointments'), 0) = 0 and not (data ? 'places'))
);`,
    );
  }
  const which = update
    ? `(collection, key) in (${keys.join(', ')}) and (status = 'draft' or has_changes)`
    : `status = 'draft'`;
  lines.push(
    `do $$
declare ids uuid[];
begin
  select array_agg(id) into ids from public.content_documents where ${which} and cardinality(public.content_validate(collection, data)) = 0;
  if ids is not null then
    perform public.content_publish_internal(ids, '${update ? 'Content update from the app repository' : 'Initial import'}');
  end if;
end $$;`,
    'commit;',
    '',
  );
  return lines.join('\n');
}

for (const [file, update] of [['seed.sql', false], ['seed-update.sql', true]] as const) {
  const out = join(__dirname, '..', 'supabase', file);
  writeFileSync(out, build(update));
  console.log(`Wrote ${out}`);
}

/** seed-prune.sql: removes EVERY document that is not in the bundled content (npm run db:update-content -- --prune). */
{
  const keys: string[] = [];
  for (const c of COLLECTIONS as CollectionName[]) {
    const value = (seed as Record<string, unknown>)[c];
    const docs = (Array.isArray(value) ? value : [value]) as Record<string, unknown>[];
    for (const d of docs) keys.push(`('${c}', '${documentKey(c, d).replace(/'/g, "''")}')`);
  }
  const out = join(__dirname, '..', 'supabase', 'seed-prune.sql');
  writeFileSync(out, [
    '-- GENERATED by scripts/content-seed-sql.ts — do not edit by hand.',
    '-- Deletes every content document that is not part of src/content/seed.ts (including editors\' own documents).',
    'begin;',
    `delete from public.content_documents where not (collection, key) in (${keys.join(', ')});`,
    'commit;',
    '',
  ].join('\n'));
  console.log(`Wrote ${out}`);
}
