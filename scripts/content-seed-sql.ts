/// <reference types="node" />
/**
 * Generates supabase/seed.sql from the bundled seed content (src/content/seed.ts).
 * Run: npm run db:seed-sql
 *
 * Every document is inserted as a draft; documents that pass `content_validate`
 * are then published in one release. The rest stay as drafts for editors to finish
 * in the CMS (e.g. guides that still need official sources).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { COLLECTIONS, type CollectionName, documentKey } from '../src/content/collections';
import * as seed from '../src/content/seed';

const lines: string[] = [
  '-- GENERATED by scripts/content-seed-sql.ts — do not edit by hand.',
  '-- Initial content imported from src/content/seed.ts.',
  'begin;',
];

for (const c of COLLECTIONS as CollectionName[]) {
  const value = (seed as Record<string, unknown>)[c];
  const docs = (Array.isArray(value) ? value : [value]) as Record<string, unknown>[];
  docs.forEach((d, i) => {
    const json = JSON.stringify(d);
    if (json.includes('$seed$')) throw new Error('Unexpected delimiter in content');
    lines.push(
      `insert into public.content_documents (collection, key, data, sort_order) values ('${c}', '${documentKey(c, d).replace(/'/g, "''")}', $seed$${json}$seed$::jsonb, ${i * 10}) on conflict (collection, key) do nothing;`,
    );
  });
}

lines.push(
  `do $$ begin
  perform public.content_publish_internal(
    (select array_agg(id) from public.content_documents where status = 'draft' and cardinality(public.content_validate(collection, data)) = 0),
    'Initial import'
  );
end $$;`,
  'commit;',
  '',
);

const out = join(__dirname, '..', 'supabase', 'seed.sql');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out}`);
